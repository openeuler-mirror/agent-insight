function parseFrameworks(raw: string | null): { value: string; label: string }[] {
    if (!raw) return [];
    const wanted = new Set(raw.split(',').map(s => s.trim().toLowerCase()).filter(Boolean));
    return FRAMEWORKS.filter(f => wanted.has(f.value));
}

function queryFlagEnabled(raw: string | null): boolean {
    return raw !== null && !['0', 'false', 'no'].includes(raw.trim().toLowerCase());
}

function detectPlatform(request: Request): 'windows' | 'unix' {
    const userAgent = request.headers.get('user-agent') || '';
    const platformHeader = request.headers.get('x-platform') || '';
    
    if (platformHeader) {
        return platformHeader.toLowerCase() === 'windows' ? 'windows' : 'unix';
    }
    
    if (userAgent.toLowerCase().includes('windows')) {
        return 'windows';
    }
    
    return 'unix';
}

function qwenSetupProtocol(request: Request): 'http' | 'https' {
    const forwardedProtocol = request.headers.get('x-forwarded-proto')?.split(',')[0]?.trim().toLowerCase();
    if (forwardedProtocol === 'http' || forwardedProtocol === 'https') return forwardedProtocol;

    return new URL(request.url).protocol === 'http:' ? 'http' : 'https';
}

function bashDoubleQuoted(value: string): string {
    return value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$').replace(/`/g, '\\`');
}

function powerShellDoubleQuoted(value: string): string {
    return value.replace(/`/g, '``').replace(/"/g, '`"').replace(/\$/g, '`$');
}

