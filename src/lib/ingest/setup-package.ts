import packageMetadata from "../../../package.json"

export function getAgentInsightClientPackageSpec(): string {
  const override = process.env.AGENT_INSIGHT_CLIENT_PACKAGE_SPEC?.trim()
  if (override) return override
  return `${packageMetadata.name}@${packageMetadata.version}`
}

export function getAgentInsightRasBashInstaller(): string {
  return [
    "install_agent_insight_ras() {",
    '    local ras_host="$1"',
    '    local ras_api_key="$2"',
    '    local ras_tmp=""',
    '    local ras_tarball_name=""',
    '    local ras_attempt=""',
    "",
    '    if [ "${AGENT_INSIGHT_RAS:-1}" = "0" ]; then',
    '        echo "ℹ️  Agent RAS [disabled]: AGENT_INSIGHT_RAS=0"',
    "        return 0",
    "    fi",
    "",
    "    # 取制品的三级回退。npm 曾是唯一来源，导致仓库外执行拿到版本号相同但",
    "    # 内容滞后的旧包，内网环境更是直接失败。服务端自己就有源码，优先问它。",
    "    # 1) 本地 checkout —— 开发者改完立即生效",
    '    if [ -f "./scripts/install-ras.js" ] && [ -f "./agent_ras/pyproject.toml" ]; then',
    '        echo "    using local clone"',
    '        AGENT_INSIGHT_HOST="$ras_host" AGENT_INSIGHT_API_KEY="$ras_api_key" node "./scripts/install-ras.js"',
    "        return $?",
    "    fi",
    "",
    "    # 2) 服务端下发 —— 与执行目录、npm registry 均无关",
    '    if command -v tar >/dev/null 2>&1; then',
    '        ras_tmp=$(mktemp -d "${TMPDIR:-/tmp}/agent-insight-ras.XXXXXX") || ras_tmp=""',
    '        if [ -n "$ras_tmp" ] && curl -fsSL -H "x-witty-api-key: $ras_api_key" "$ras_host/api/ingest/setup/bundle?name=ras" -o "$ras_tmp/ras.tar.gz" 2>/dev/null; then',
    '            mkdir -p "$ras_tmp/extracted"',
    '            if tar -xzf "$ras_tmp/ras.tar.gz" -C "$ras_tmp/extracted" 2>/dev/null && [ -f "$ras_tmp/extracted/scripts/install-ras.js" ]; then',
    '                echo "    using server-provided bundle"',
    '                AGENT_INSIGHT_HOST="$ras_host" AGENT_INSIGHT_API_KEY="$ras_api_key" node "$ras_tmp/extracted/scripts/install-ras.js"',
    "                local ras_bundle_status=$?",
    '                rm -rf -- "$ras_tmp"',
    "                return $ras_bundle_status",
    "            fi",
    "        fi",
    '        [ -n "$ras_tmp" ] && rm -rf -- "$ras_tmp"',
    '        ras_tmp=""',
    "    fi",
    "",
    "    # 3) npm 兜底 —— 仅在服务端过旧、尚无 bundle 接口时才会走到",
    '    if ! command -v npm >/dev/null 2>&1 || ! command -v tar >/dev/null 2>&1; then',
    '        echo "❌ Agent RAS [failed]: npm and tar are required"',
    "        return 1",
    "    fi",
    "",
    '    ras_tmp=$(mktemp -d "${TMPDIR:-/tmp}/agent-insight-ras.XXXXXX") || {',
    '        echo "❌ Agent RAS [failed]: unable to create a temporary directory"',
    "        return 1",
    "    }",
    "",
    "    for ras_attempt in 1 2 3; do",
    '        mkdir -p "$ras_tmp/npm-cache-$ras_attempt"',
    '        if ras_tarball_name=$(NPM_CONFIG_CACHE="$ras_tmp/npm-cache-$ras_attempt" npm pack --ignore-scripts --pack-destination "$ras_tmp" "$AGENT_INSIGHT_PACKAGE_SPEC" 2>"$ras_tmp/npm-pack-$ras_attempt.log" | tail -n 1); then',
    "            break",
    "        fi",
    '        echo "⚠️  Agent RAS package download attempt $ras_attempt/3 failed"',
    '        tail -n 20 "$ras_tmp/npm-pack-$ras_attempt.log" 2>/dev/null || true',
    '        ras_tarball_name=""',
    "    done",
    "",
    '    if [ -z "$ras_tarball_name" ] || [ ! -f "$ras_tmp/$ras_tarball_name" ]; then',
    '        echo "❌ Agent RAS [failed]: unable to download $AGENT_INSIGHT_PACKAGE_SPEC"',
    '        rm -rf -- "$ras_tmp"',
    "        return 1",
    "    fi",
    "",
    '    mkdir -p "$ras_tmp/extracted"',
    '    if ! tar -xzf "$ras_tmp/$ras_tarball_name" -C "$ras_tmp/extracted"; then',
    '        echo "❌ Agent RAS [failed]: unable to extract package tarball"',
    '        rm -rf -- "$ras_tmp"',
    "        return 1",
    "    fi",
    "",
    '    if [ ! -f "$ras_tmp/extracted/package/scripts/install-ras.js" ] || [ ! -f "$ras_tmp/extracted/package/agent_ras/pyproject.toml" ]; then',
    '        echo "❌ Agent RAS [failed]: $AGENT_INSIGHT_PACKAGE_SPEC does not contain the RAS installer/runtime"',
    '        rm -rf -- "$ras_tmp"',
    "        return 1",
    "    fi",
    "",
    '    AGENT_INSIGHT_HOST="$ras_host" AGENT_INSIGHT_API_KEY="$ras_api_key" node "$ras_tmp/extracted/package/scripts/install-ras.js"',
    "    local ras_status=$?",
    '    if [ "$ras_status" -eq 0 ] && [ -n "$ras_host" ] && [ -n "$ras_api_key" ]; then',
    '        local ras_events_url="$ras_host"',
    '        case "$ras_events_url" in http://*|https://*) ;; *) ras_events_url="http://$ras_events_url" ;; esac',
    '        ras_events_url="${ras_events_url%/}/api/ingest/ras-events?taskId=__agent_insight_ras_preflight__"',
    '        if curl -sSf --max-time 60 -H "x-witty-api-key: $ras_api_key" "$ras_events_url" >/dev/null; then',
    '            echo "✅ Agent RAS ingest preflight ready"',
    "        else",
    '            echo "⚠️  Agent RAS ingest preflight failed; runtime installation remains available"',
    "        fi",
    "    fi",
    '    rm -rf -- "$ras_tmp"',
    "    return $ras_status",
    "}",
  ].join("\n")
}

export function getAgentInsightBashDownloadHelper(): string {
  return [
    "download_agent_insight_component() {",
    '    local component_url="$1"',
    '    local component_target="$2"',
    '    local component_label="$3"',
    '    local component_tmp="${component_target}.tmp.$$"',
    "",
    '    mkdir -p "$(dirname "$component_target")"',
    '    if curl -sSf "$component_url" -o "$component_tmp"; then',
    '        mv -f "$component_tmp" "$component_target"',
    '        echo "✅ $component_label ready"',
    "        return 0",
    "    fi",
    '    rm -f -- "$component_tmp"',
    '    echo "❌ Failed to download $component_label from $component_url"',
    "    return 1",
    "}",
  ].join("\n")
}

export function getAgentInsightClientBashInstaller(): string {
  return [
        'install_agent_insight_client() {',
        '    local host="$1" api_key="$2"',
        '    if [ -z "$api_key" ]; then',
        '        echo "⚠️  跳过常驻客户端注册：缺少 API Key"',
        '        return 1',
        '    fi',
        '',
        '    # 这里不能因为「配置文件已存在」就跳过：换账号后本机仍绑在原账号上，',
        '    # 而 .env 已被改写成新账号 —— Trace 归新账号、纳管归旧账号，机器裂成两半。',
        '    # 安装器每次都会刷新注册；同机同账号由服务端复用记录并轮换设备凭证。',
        '',
        '    local token_json token token_user',
        '    token_json=$(curl -sSf -X POST "$host/api/reliability/install-tokens" -H "content-type: application/json" -H "x-witty-api-key: $api_key" -d "{\\"expiresInSeconds\\":600}" 2>/dev/null) || {',
        '        echo "⚠️  常驻客户端注册失败：无法获取安装令牌"',
        '        return 1',
        '    }',
        '    token=$(printf "%s" "$token_json" | node -e "let s=\'\';process.stdin.on(\'data\',d=>s+=d).on(\'end\',()=>{try{process.stdout.write(JSON.parse(s).installToken||\'\')}catch{}})" 2>/dev/null)',
        '    token_user=$(printf "%s" "$token_json" | node -e "let s=\'\';process.stdin.on(\'data\',d=>s+=d).on(\'end\',()=>{try{process.stdout.write(JSON.parse(s).user||\'\')}catch{}})" 2>/dev/null)',
        '    if [ -z "$token" ]; then',
        '        echo "⚠️  常驻客户端注册失败：安装令牌为空"',
        '        return 1',
        '    fi',
        '',
        '    # 常驻客户端默认使用当前服务端下发的 bundle，避免执行目录里的旧 checkout',
        '    # 覆盖服务端修复。开发调试时可显式设置 AGENT_INSIGHT_CLIENT_SOURCE=local。',
        '    if [ "${AGENT_INSIGHT_CLIENT_SOURCE:-server}" = "local" ]; then',
        '        if [ ! -f "./scripts/install-ras-client.js" ]; then',
        '            echo "⚠️  常驻客户端注册失败：已指定本地源码，但当前目录没有 ./scripts/install-ras-client.js"',
        '            return 1',
        '        fi',
        '        echo "    使用显式指定的本地常驻客户端安装器"',
        '        AGENT_INSIGHT_HOST="$host" node "./scripts/install-ras-client.js" --host "$host" --token "$token" --user "$token_user" --frameworks "$SELECTED_FRAMEWORKS"',
        '        return $?',
        '    fi',
        '',
        '    local pkg_tmp_root pkg_tmp tarball rc',
        '    pkg_tmp_root="$AGENT_INSIGHT_HOME/client/tmp"',
        '    mkdir -p "$pkg_tmp_root" || {',
        '        echo "⚠️  常驻客户端注册失败：无法创建安装暂存目录 $pkg_tmp_root"',
        '        return 1',
        '    }',
        '    chmod 700 "$pkg_tmp_root" 2>/dev/null || true',
        '    pkg_tmp=$(mktemp -d "$pkg_tmp_root/install.XXXXXX") || {',
        '        echo "⚠️  常驻客户端注册失败：无法创建安装临时目录"',
        '        return 1',
        '    }',
        '    if curl -fsSL -H "x-witty-api-key: $api_key" "$host/api/ingest/setup/bundle?name=client" -o "$pkg_tmp/client.tar.gz" 2>/dev/null; then',
        '        mkdir -p "$pkg_tmp/x" && tar -xzf "$pkg_tmp/client.tar.gz" -C "$pkg_tmp/x" 2>/dev/null',
        '        if [ -f "$pkg_tmp/x/scripts/install-ras-client.js" ]; then',
        '            printf \'%s\\n\' \'{"type":"commonjs"}\' > "$pkg_tmp/x/scripts/package.json"',
        '            AGENT_INSIGHT_HOST="$host" node "$pkg_tmp/x/scripts/install-ras-client.js" --host "$host" --token "$token" --user "$token_user" --frameworks "$SELECTED_FRAMEWORKS"',
        '            rc=$?',
        '            rm -rf -- "$pkg_tmp"',
        '            return $rc',
        '        fi',
        '    fi',
        '',
        '    ( cd "$pkg_tmp" && npm pack "$AGENT_INSIGHT_PACKAGE_SPEC" >/dev/null 2>&1 ) || true',
        '    tarball=$(ls "$pkg_tmp"/*.tgz 2>/dev/null | head -n 1)',
        '    if [ -n "$tarball" ]; then',
        '        mkdir -p "$pkg_tmp/x" && tar -xzf "$tarball" -C "$pkg_tmp/x" 2>/dev/null',
        '    fi',
        '    if [ -f "$pkg_tmp/x/package/scripts/install-ras-client.js" ]; then',
        '        printf \'%s\\n\' \'{"type":"commonjs"}\' > "$pkg_tmp/x/package/scripts/package.json"',
        '        AGENT_INSIGHT_HOST="$host" node "$pkg_tmp/x/package/scripts/install-ras-client.js" --host "$host" --token "$token" --user "$token_user" --frameworks "$SELECTED_FRAMEWORKS"',
        '        rc=$?',
        '    else',
        '        echo "⚠️  常驻客户端注册失败：服务端未提供客户端制品，且 $AGENT_INSIGHT_PACKAGE_SPEC 不含安装器"',
        '        rc=1',
        '    fi',
        '    rm -rf -- "$pkg_tmp"',
        '    return $rc',
        '}',
  ].join('\n')
}
