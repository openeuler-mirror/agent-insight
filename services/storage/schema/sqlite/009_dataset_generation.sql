CREATE TABLE dataset_generation_jobs (
  workspace_id TEXT NOT NULL,
  job_id TEXT NOT NULL,
  dataset_id TEXT NOT NULL,
  actor_principal_id TEXT NOT NULL,
  request_id TEXT NOT NULL,
  request_hash TEXT NOT NULL,
  config_hash TEXT NOT NULL,
  config_ref TEXT NOT NULL,
  members_hash TEXT NOT NULL,
  members_ref TEXT NOT NULL,
  status TEXT NOT NULL CHECK(status IN ('queued','running','succeeded','failed','deleted')),
  stage TEXT NOT NULL,
  stage_index INTEGER NOT NULL CHECK(stage_index BETWEEN 0 AND 6) CHECK(stage_index IS NULL OR typeof(stage_index)='integer'),
  generated_count INTEGER NOT NULL CHECK(generated_count>=0) CHECK(generated_count IS NULL OR typeof(generated_count)='integer'),
  attempt_count INTEGER NOT NULL DEFAULT 0 CHECK(attempt_count>=0) CHECK(attempt_count IS NULL OR typeof(attempt_count)='integer'),
  epoch INTEGER NOT NULL CHECK(epoch>=0) CHECK(epoch IS NULL OR typeof(epoch)='integer'),
  revision INTEGER NOT NULL CHECK(revision>=1) CHECK(revision IS NULL OR typeof(revision)='integer'),
  dataset_revision INTEGER NOT NULL CHECK(dataset_revision>=1) CHECK(dataset_revision IS NULL OR typeof(dataset_revision)='integer'),
  dataset_lifecycle_revision INTEGER NOT NULL CHECK(dataset_lifecycle_revision>=1) CHECK(dataset_lifecycle_revision IS NULL OR typeof(dataset_lifecycle_revision)='integer'),
  lease_owner TEXT,
  lease_until_ms INTEGER CHECK(lease_until_ms IS NULL OR typeof(lease_until_ms)='integer'),
  summary_hash TEXT,
  summary_ref TEXT,
  capture_hash TEXT,
  capture_ref TEXT,
  result_hash TEXT,
  error_code TEXT,
  error_message TEXT,
  deletion_id TEXT,
  created_at_ms INTEGER NOT NULL CHECK(created_at_ms>=0) CHECK(created_at_ms IS NULL OR typeof(created_at_ms)='integer'),
  updated_at_ms INTEGER NOT NULL CHECK(updated_at_ms>=created_at_ms) CHECK(updated_at_ms IS NULL OR typeof(updated_at_ms)='integer'),
  PRIMARY KEY(workspace_id,job_id),
  UNIQUE(workspace_id,dataset_id),
  UNIQUE(workspace_id,actor_principal_id,request_id),
  UNIQUE(workspace_id,deletion_id),
  FOREIGN KEY(workspace_id,dataset_id) REFERENCES dataset_compat_heads(workspace_id,dataset_id),
  FOREIGN KEY(actor_principal_id) REFERENCES iam_principals(principal_id),
  CHECK(length(request_hash)=64 AND length(config_hash)=64 AND length(members_hash)=64),
  CHECK((lease_owner IS NULL AND lease_until_ms IS NULL) OR (lease_owner IS NOT NULL AND lease_until_ms IS NOT NULL)),
  CHECK((summary_hash IS NULL AND summary_ref IS NULL) OR (summary_hash IS NOT NULL AND summary_ref IS NOT NULL AND length(summary_hash)=64)),
  CHECK((capture_hash IS NULL AND capture_ref IS NULL) OR (capture_hash IS NOT NULL AND capture_ref IS NOT NULL AND length(capture_hash)=64)),
  CHECK((status='running' AND lease_owner IS NOT NULL AND lease_until_ms IS NOT NULL) OR (status<>'running' AND lease_owner IS NULL AND lease_until_ms IS NULL)),
  CHECK((status='deleted')=(deletion_id IS NOT NULL)),
  CHECK(status NOT IN ('succeeded','failed') OR (result_hash IS NOT NULL AND length(result_hash)=64)),
  CHECK(lease_until_ms IS NULL OR lease_until_ms>=0),
  CHECK(length(config_ref)>0 AND length(members_ref)>0)
);
CREATE INDEX idx_dataset_generation_actor ON dataset_generation_jobs(workspace_id,actor_principal_id,status,created_at_ms);
CREATE TRIGGER dataset_generation_guard BEFORE UPDATE ON dataset_generation_jobs WHEN OLD.workspace_id IS NOT NEW.workspace_id OR OLD.job_id IS NOT NEW.job_id OR OLD.dataset_id IS NOT NEW.dataset_id OR OLD.actor_principal_id IS NOT NEW.actor_principal_id OR OLD.request_id IS NOT NEW.request_id OR OLD.request_hash IS NOT NEW.request_hash OR OLD.config_hash IS NOT NEW.config_hash OR OLD.config_ref IS NOT NEW.config_ref OR OLD.members_hash IS NOT NEW.members_hash OR OLD.members_ref IS NOT NEW.members_ref OR OLD.created_at_ms IS NOT NEW.created_at_ms OR OLD.dataset_lifecycle_revision IS NOT NEW.dataset_lifecycle_revision OR NEW.revision<>OLD.revision+1 OR NEW.epoch<OLD.epoch OR (OLD.status IN ('succeeded','failed','deleted') AND NEW.status<>OLD.status AND NEW.status<>'deleted') BEGIN SELECT RAISE(ABORT,'invalid generation transition'); END;
CREATE TRIGGER dataset_generation_keep BEFORE DELETE ON dataset_generation_jobs BEGIN SELECT RAISE(ABORT,'generation receipts retained'); END;
