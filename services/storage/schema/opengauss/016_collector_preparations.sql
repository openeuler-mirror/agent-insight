CREATE TABLE collector_preparation_receipts (
  workspace_id TEXT NOT NULL,
  scope_kind TEXT NOT NULL,
  scope_key TEXT NOT NULL,
  operation_key TEXT NOT NULL,
  owner_principal_id TEXT NOT NULL,
  trace_id TEXT,
  operation_kind TEXT NOT NULL,
  input_hash TEXT NOT NULL,
  input_text_hash TEXT NOT NULL,
  input_text_ref TEXT NOT NULL,
  context_hash TEXT NOT NULL,
  context_ref TEXT NOT NULL,
  capture_hash TEXT,
  capture_ref TEXT,
  plan_hash TEXT,
  plan_ref TEXT,
  seal_revision BIGINT NOT NULL DEFAULT 1,
  created_at_ms BIGINT NOT NULL,
  updated_at_ms BIGINT NOT NULL,
  PRIMARY KEY (workspace_id,scope_kind,scope_key,operation_key),
  FOREIGN KEY (workspace_id) REFERENCES workspaces (workspace_id) ON DELETE NO ACTION,
  FOREIGN KEY (owner_principal_id) REFERENCES iam_principals (principal_id) ON DELETE NO ACTION,
  FOREIGN KEY (workspace_id,trace_id) REFERENCES trace_locators (workspace_id,trace_id) ON DELETE NO ACTION,
  CHECK (scope_kind IN ('source','thread')),
  CHECK (length(scope_key) BETWEEN 1 AND 512),
  CHECK (length(operation_key) BETWEEN 1 AND 512),
  CHECK (operation_kind IN ('snapshot','complete','thread_only')),
  CHECK ((scope_kind='source' AND trace_id IS NOT NULL AND scope_key=trace_id AND operation_kind IN ('snapshot','complete')) OR (scope_kind='thread' AND trace_id IS NULL AND operation_kind='thread_only')),
  CHECK ((capture_hash IS NULL)=(capture_ref IS NULL)),
  CHECK ((plan_hash IS NULL)=(plan_ref IS NULL)),
  CHECK (plan_hash IS NULL OR capture_hash IS NOT NULL),
  CHECK (length(input_hash)=64 AND input_hash ~ '^[0-9a-f]{64}$'),
  CHECK (length(input_text_hash)=64 AND input_text_hash ~ '^[0-9a-f]{64}$'),
  CHECK (length(context_hash)=64 AND context_hash ~ '^[0-9a-f]{64}$'),
  CHECK (capture_hash IS NULL OR (length(capture_hash)=64 AND capture_hash ~ '^[0-9a-f]{64}$')),
  CHECK (plan_hash IS NULL OR (length(plan_hash)=64 AND plan_hash ~ '^[0-9a-f]{64}$')),
  CHECK (input_text_ref IS NULL OR length(input_text_ref) BETWEEN 1 AND 4096),
  CHECK (context_ref IS NULL OR length(context_ref) BETWEEN 1 AND 4096),
  CHECK (capture_ref IS NULL OR length(capture_ref) BETWEEN 1 AND 4096),
  CHECK (plan_ref IS NULL OR length(plan_ref) BETWEEN 1 AND 4096),
  CHECK (seal_revision>=1 AND seal_revision<=9223372036854775807),
  CHECK (created_at_ms>=0 AND created_at_ms<=9223372036854775807),
  CHECK (updated_at_ms>=0 AND updated_at_ms<=9223372036854775807),
  CHECK (updated_at_ms>=created_at_ms),
  CHECK (seal_revision=1+(CASE WHEN capture_hash IS NULL THEN 0 ELSE 1 END)+(CASE WHEN plan_hash IS NULL THEN 0 ELSE 1 END))
);
CREATE INDEX idx_collector_preparation_owner ON collector_preparation_receipts (workspace_id,owner_principal_id,created_at_ms,scope_kind,scope_key);
CREATE FUNCTION collector_preparation_update_guard() RETURNS trigger AS $$ BEGIN IF NEW.workspace_id IS DISTINCT FROM OLD.workspace_id OR NEW.scope_kind IS DISTINCT FROM OLD.scope_kind OR NEW.scope_key IS DISTINCT FROM OLD.scope_key OR NEW.operation_key IS DISTINCT FROM OLD.operation_key OR NEW.owner_principal_id IS DISTINCT FROM OLD.owner_principal_id OR NEW.trace_id IS DISTINCT FROM OLD.trace_id OR NEW.operation_kind IS DISTINCT FROM OLD.operation_kind OR NEW.input_hash IS DISTINCT FROM OLD.input_hash OR NEW.input_text_hash IS DISTINCT FROM OLD.input_text_hash OR NEW.input_text_ref IS DISTINCT FROM OLD.input_text_ref OR NEW.context_hash IS DISTINCT FROM OLD.context_hash OR NEW.context_ref IS DISTINCT FROM OLD.context_ref OR NEW.created_at_ms IS DISTINCT FROM OLD.created_at_ms OR (OLD.capture_hash IS NOT NULL AND (NEW.capture_hash IS DISTINCT FROM OLD.capture_hash OR NEW.capture_ref IS DISTINCT FROM OLD.capture_ref)) OR (OLD.plan_hash IS NOT NULL AND (NEW.plan_hash IS DISTINCT FROM OLD.plan_hash OR NEW.plan_ref IS DISTINCT FROM OLD.plan_ref)) OR NEW.updated_at_ms<OLD.updated_at_ms OR NEW.seal_revision<>OLD.seal_revision+1 THEN RAISE EXCEPTION 'collector preparation identity and sealed slots are immutable'; END IF; RETURN NEW; END; $$ LANGUAGE plpgsql;
CREATE FUNCTION collector_preparation_delete_guard() RETURNS trigger AS $$ BEGIN RAISE EXCEPTION 'collector preparation history is retained'; RETURN OLD; END; $$ LANGUAGE plpgsql;
CREATE TRIGGER collector_preparation_update_guard BEFORE UPDATE ON collector_preparation_receipts FOR EACH ROW EXECUTE PROCEDURE collector_preparation_update_guard();
CREATE TRIGGER collector_preparation_delete_guard BEFORE DELETE ON collector_preparation_receipts FOR EACH ROW EXECUTE PROCEDURE collector_preparation_delete_guard();
