CREATE TABLE dataset_generation_jobs (
  workspace_id TEXT NOT NULL,
  job_id TEXT NOT NULL,
  dataset_id TEXT NOT NULL,
  actor_principal_id TEXT NOT NULL,
  request_id TEXT NOT NULL,
  request_hash TEXT NOT NULL,
  config_hash TEXT NOT NULL,
  config_ref TEXT NOT NULL,
  members_hash TEXT NOT NULL,
  members_ref TEXT NOT NULL,
  status TEXT NOT NULL CHECK(status IN ('queued','running','succeeded','failed','deleted')),
  stage TEXT NOT NULL,
  stage_index BIGINT NOT NULL CHECK(stage_index BETWEEN 0 AND 6),
  generated_count BIGINT NOT NULL CHECK(generated_count>=0),
  attempt_count BIGINT NOT NULL DEFAULT 0 CHECK(attempt_count>=0),
  epoch BIGINT NOT NULL CHECK(epoch>=0),
  revision BIGINT NOT NULL CHECK(revision>=1),
  dataset_revision BIGINT NOT NULL CHECK(dataset_revision>=1),
  dataset_lifecycle_revision BIGINT NOT NULL CHECK(dataset_lifecycle_revision>=1),
  lease_owner TEXT,
  lease_until_ms BIGINT,
  summary_hash TEXT,
  summary_ref TEXT,
  capture_hash TEXT,
  capture_ref TEXT,
  result_hash TEXT,
  error_code TEXT,
  error_message TEXT,
  deletion_id TEXT,
  created_at_ms BIGINT NOT NULL CHECK(created_at_ms>=0),
  updated_at_ms BIGINT NOT NULL CHECK(updated_at_ms>=created_at_ms),
  PRIMARY KEY(workspace_id,job_id),
  UNIQUE(workspace_id,dataset_id),
  UNIQUE(workspace_id,actor_principal_id,request_id),
  UNIQUE(workspace_id,deletion_id),
  FOREIGN KEY(workspace_id,dataset_id) REFERENCES dataset_compat_heads(workspace_id,dataset_id),
  FOREIGN KEY(actor_principal_id) REFERENCES iam_principals(principal_id),
  CHECK(length(request_hash)=64 AND length(config_hash)=64 AND length(members_hash)=64),
  CHECK((lease_owner IS NULL AND lease_until_ms IS NULL) OR (lease_owner IS NOT NULL AND lease_until_ms IS NOT NULL)),
  CHECK((summary_hash IS NULL AND summary_ref IS NULL) OR (summary_hash IS NOT NULL AND summary_ref IS NOT NULL AND length(summary_hash)=64)),
  CHECK((capture_hash IS NULL AND capture_ref IS NULL) OR (capture_hash IS NOT NULL AND capture_ref IS NOT NULL AND length(capture_hash)=64)),
  CHECK((status='running' AND lease_owner IS NOT NULL AND lease_until_ms IS NOT NULL) OR (status<>'running' AND lease_owner IS NULL AND lease_until_ms IS NULL)),
  CHECK((status='deleted')=(deletion_id IS NOT NULL)),
  CHECK(status NOT IN ('succeeded','failed') OR (result_hash IS NOT NULL AND length(result_hash)=64)),
  CHECK(lease_until_ms IS NULL OR lease_until_ms>=0),
  CHECK(length(config_ref)>0 AND length(members_ref)>0)
);
CREATE INDEX idx_dataset_generation_actor ON dataset_generation_jobs(workspace_id,actor_principal_id,status,created_at_ms);
CREATE FUNCTION guard_dataset_generation() RETURNS trigger AS $$ BEGIN IF TG_OP='DELETE' THEN RAISE EXCEPTION 'generation receipts retained'; END IF; IF OLD.workspace_id IS DISTINCT FROM NEW.workspace_id OR OLD.job_id IS DISTINCT FROM NEW.job_id OR OLD.dataset_id IS DISTINCT FROM NEW.dataset_id OR OLD.actor_principal_id IS DISTINCT FROM NEW.actor_principal_id OR OLD.request_id IS DISTINCT FROM NEW.request_id OR OLD.request_hash IS DISTINCT FROM NEW.request_hash OR OLD.config_hash IS DISTINCT FROM NEW.config_hash OR OLD.config_ref IS DISTINCT FROM NEW.config_ref OR OLD.members_hash IS DISTINCT FROM NEW.members_hash OR OLD.members_ref IS DISTINCT FROM NEW.members_ref OR OLD.created_at_ms IS DISTINCT FROM NEW.created_at_ms OR OLD.dataset_lifecycle_revision IS DISTINCT FROM NEW.dataset_lifecycle_revision OR NEW.revision<>OLD.revision+1 OR NEW.epoch<OLD.epoch OR (OLD.status IN ('succeeded','failed','deleted') AND NEW.status<>OLD.status AND NEW.status<>'deleted') THEN RAISE EXCEPTION 'invalid generation transition'; END IF; RETURN NEW; END; $$ LANGUAGE plpgsql;
CREATE TRIGGER dataset_generation_guard BEFORE UPDATE OR DELETE ON dataset_generation_jobs FOR EACH ROW EXECUTE PROCEDURE guard_dataset_generation();
