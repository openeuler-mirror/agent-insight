const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const base = process.env.TRACE_UI_URL || 'http://localhost:3000';
const out = process.env.TRACE_UI_EVIDENCE || __dirname;
(async () => {
  fs.mkdirSync(out, { recursive: true });
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1050 } });
    const credentials = await (await context.request.post(`${base}/api/auth/apikey`, { data: { username: 'admin' } })).json();
    assert.ok(credentials.apiKey);
    await context.addInitScript(({ apiKey }) => { localStorage.setItem('user_id', 'admin'); localStorage.setItem('api_key', apiKey); }, credentials);
    const headers = { 'x-witty-api-key': credentials.apiKey };
    const page = await context.newPage(), errors = [];
    page.on('pageerror', e => errors.push(e.message));
    const name = `Trace UI ${Date.now()}`, failedName = `${name} 失败`;
    const shot = n => page.screenshot({ path: path.join(out, `${n}.png`), fullPage: true });
    const create = async (title, agent) => {
      await page.goto(`${base}/dataset`);
      await page.getByRole('button', { name: '展开新建方式' }).click();
      await page.getByRole('menuitem', { name: '基于 Trace 生成' }).click();
      assert.ok(await page.getByRole('button', { name: '开始生成', exact: true }).isDisabled());
      await page.getByRole('textbox', { name: '名称', exact: true }).fill(title);
      await page.getByRole('combobox', { name: 'Agent 平台', exact: true }).selectOption('codex');
      await page.getByRole('combobox', { name: 'Agent', exact: true }).selectOption({ label: agent });
      await shot(title === name ? '01-config' : '06-failure-config');
      const response = page.waitForResponse(r => r.url().endsWith('/api/agent-datasets/trace-generation') && r.request().method() === 'POST');
      await page.getByRole('button', { name: '开始生成', exact: true }).click();
      const accepted = await response; assert.equal(accepted.status(), 202); return (await accepted.json()).datasetId;
    };
    const published = await create(name, 'UI Test Agent（5 条 Trace）');
    await page.waitForFunction(() => [...document.querySelectorAll('button')].some(b => b.textContent === '完成' && !b.disabled), {}, { timeout: 90000 });
    await shot('02-published'); await page.getByRole('button', { name: '完成', exact: true }).click();
    const card = page.getByRole('link', { name: `查看数据集 ${name}`, exact: true });
    await card.getByRole('button', { name: '编辑信息' }).click();
    await page.getByRole('dialog').locator('input').first().fill(`${name} 已编辑`);
    await page.getByRole('button', { name: '保存评测集' }).click();
    await page.getByRole('link', { name: `查看数据集 ${name} 已编辑`, exact: true }).click();
    await page.getByRole('button', { name: '新增字段', exact: true }).waitFor();
    assert.ok(await page.getByRole('button', { name: '新增字段', exact: true }).isDisabled()); await shot('03-detail');
    const original = await (await context.request.get(`${base}/api/agent-datasets/${published}?user=admin`, { headers })).json();
    assert.equal(original.cases.length, 4);
    const groups = new Map(); for (const c of original.cases) groups.set(c.input, (groups.get(c.input) || 0) + 1);
    assert.ok([...groups.values()].some(n => n > 1));
    assert.equal((await context.request.get(`${base}/api/agent-datasets/${published}?user=admin`)).status(), 401);
    assert.equal((await context.request.get(`${base}/api/agent-datasets/${published}?user=other`, { headers })).status(), 404);
    assert.equal((await context.request.post(`${base}/api/agent-datasets/trace-generation?user=admin`, { data: {} })).status(), 401);
    assert.equal((await context.request.patch(`${base}/api/agent-datasets`, { headers, data: { user: 'admin', id: published, fields: null } })).status(), 422);
    const patch = data => context.request.patch(`${base}/api/agent-datasets`, { headers, data: { user: 'admin', id: published, ...data } });
    assert.equal((await patch({ cases: [{ id: 'bad', values: { input: '', reference_output: 'a' } }] })).status(), 422);
    await page.goto(`${base}/dataset`);
    await page.getByRole('link', { name: `查看数据集 ${name} 已编辑`, exact: true }).getByRole('button', { name: '发起评测' }).click();
    await page.waitForURL('**/experiments/new?datasetId=*'); await shot('04-evaluation');
    const experimentResponse = await context.request.post(`${base}/api/experiments`, { headers, data: { user: 'admin', name: `${name} 快照`, agentName: 'UI Test Agent', datasetId: published, evaluatorIds: ['task-completion'], cases: original.cases.map(c => ({ datasetId: published, datasetCaseId: c.id, input: 'forged', referenceOutput: 'forged', datasetInput: 'forged' })) } });
    assert.equal(experimentResponse.status(), 200, await experimentResponse.text());
    const experiment = await experimentResponse.json();
    assert.equal((await patch({ cases: [] })).status(), 200);
    await page.goto(`${base}/dataset`);
    assert.ok(await page.getByRole('link', { name: `查看数据集 ${name} 已编辑`, exact: true }).getByRole('button', { name: '发起评测' }).isDisabled());
    const failed = await create(failedName, 'Invalid Agent（1 条 Trace）');
    await page.getByRole('button', { name: '返回', exact: true }).waitFor({ timeout: 90000 }); await shot('05-failed');
    assert.ok(await page.getByRole('button', { name: '完成', exact: true }).isDisabled());
    await page.goto(`${base}/dataset`);
    const failedCard = page.getByRole('link', { name: `查看数据集 ${failedName}`, exact: true });
    await failedCard.getByRole('button', { name: '编辑信息' }).click();
    assert.equal(await page.getByRole('textbox', { name: '名称', exact: true }).inputValue(), failedName);
    await page.getByRole('button', { name: '取消', exact: true }).click();
    assert.equal((await context.request.get(`${base}/api/agent-datasets/${failed}/generation`, { headers })).status(), 200);
    await failedCard.click(); await page.getByRole('button', { name: '返回', exact: true }).click();
    await page.getByRole('textbox', { name: '名称', exact: true }).waitFor();
    assert.equal(await page.getByRole('textbox', { name: '名称', exact: true }).inputValue(), failedName);
    assert.equal((await context.request.get(`${base}/api/agent-datasets/${failed}/generation`, { headers })).status(), 404);
    await page.getByRole('combobox', { name: 'Agent', exact: true }).selectOption({ label: 'UI Test Agent（5 条 Trace）' });
    await page.getByRole('button', { name: '开始生成', exact: true }).click();
    await page.waitForFunction(() => [...document.querySelectorAll('button')].some(b => b.textContent === '完成' && !b.disabled), {}, { timeout: 90000 });
    await shot('07-recreated'); await page.getByRole('button', { name: '完成', exact: true }).click();
    assert.deepEqual(errors, []);
    fs.writeFileSync(path.join(out, 'verification.json'), JSON.stringify({ passed: true, datasetId: published, experimentId: experiment.id, frozenCases: original.cases.map(c => ({ input: c.input, referenceOutput: c.expectedOutput })), pageErrors: errors }, null, 2));
    console.log('PASS: UI generation/edit/detail/evaluation/empty set/failure/edit cancellation/cleanup/refill/recreation; API identity and schema guards.');
  } finally { await browser.close(); }
})().catch(e => { console.error(e.stack); process.exit(1); });
